package com.aiphone.assistant.ui

/**
 * 界面路由。
 *
 * 页面很少，暂时不引入 Navigation 库 —— 用最简单的状态切换就够了，
 * 少一个依赖少一层复杂度。等页面变多再换。
 *
 * 权限相关的入口**全部**收在 [PERMISSIONS] 一页里：无障碍、悬浮窗、通知、
 * 精确闹钟、副屏（Shizuku）。其他页面不许再发起权限申请，只显示状态、
 * 最多给一句"到「权限」里开"的提示。
 */
enum class Screen {
    /** 主界面：中间是纸盒 logo，底下是输入框 */
    CONTROL,

    /**
     * 权限页：所有需要用户去系统里授予的能力都在这申请。
     *
     * 单独一页而不是塞在设置里，是因为「设置」是给用户调偏好的，
     * 权限是"不开就用不了"的前置条件，性质不同、该找的位置也不同。
     */
    PERMISSIONS,

    /** 设置页：关于 / 模型 / 更多设置 */
    SETTINGS,

    /** 操作记录：手动做一遍，交给 AI 学成技能 */
    RECORDING,

    /** 定时任务：到点自动跑一条任务 */
    SCHEDULES,
}
